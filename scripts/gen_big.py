#!/usr/bin/env python3
"""Write oracle/programs/big.rs: one file, many functions and many generic
instances, for measuring an edit to one function in a crate of some size.

usage: scripts/gen_big.py [N]   (N item groups, 60 by default)
"""
import sys
from pathlib import Path

N = int(sys.argv[1]) if len(sys.argv) > 1 else 60
out = ["// Generated by scripts/gen_big.py. Many small types and functions, each",
       "// with its own generic instances, and a `main` that runs them all.",
       "",
       "use std::fmt;",
       ""]
for i in range(N):
    out.append(f"""#[derive(Debug, Clone, PartialEq)]
struct Item{i} {{
    id: u32,
    name: String,
    weight: i64,
}}

impl fmt::Display for Item{i} {{
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {{
        write!(f, "{{}}#{{}}({{}})", self.name, self.id, self.weight)
    }}
}}

fn make{i}(n: u32) -> Vec<Item{i}> {{
    (0..n)
        .map(|k| Item{i} {{ id: k * {i + 1}, name: format!("i{i}_{{k}}"), weight: (k as i64 * {7 * i + 3}) % {i + 11} - 5 }})
        .collect()
}}

fn work{i}(n: u32) -> (i64, String) {{
    let mut items = make{i}(n);
    items.sort_by_key(|it| (it.weight, it.id));
    let total: i64 = items.iter().filter(|it| it.weight > 0).map(|it| it.weight).sum();
    let names: Vec<String> = items.iter().take(3).map(|it| it.to_string()).collect();
    (total, names.join(","))
}}
""")
out.append("fn main() {")
out.append("    let mut grand = 0i64;")
for i in range(N):
    out.append(f"    let (t, s) = work{i}({5 + i % 7});")
    out.append(f"    grand += t;")
    out.append(f"    println!(\"{i}: {{t}} {{s}}\");")
out.append("    println!(\"grand total {grand}\");")
out.append("}")
Path(__file__).resolve().parent.parent.joinpath("oracle/programs/big.rs").write_text("\n".join(out) + "\n")
